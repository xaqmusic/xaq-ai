"""
maze_env.py — Fixed 5×5 maze benchmark for AMI-Ogma v3.

The third peer of HeadlessBreakout / CartPoleEnv. Unlike the two reactive
benchmarks, the maze requires temporal credit propagation: the agent must
discover that certain places eventually lead to reward even when the reward
event itself is dozens (or hundreds) of ticks away.

Body model is deliberately 1D-action (rodent-style steering) so the existing
EFEPolicy / ActionTransitionModel / NodePathBlame stack binds unchanged —
the same LEFT / IDLE / RIGHT action bins that drive Pong's paddle and
CartPole's cart now drive turn commands. Forward motion is constant; the
scalar force signal rotates the heading.

  tick()          → rendered top-down RGB frame (walls grey, agent magenta,
                    goal green) — same shape contract as HeadlessBreakout
  state()         → dict telemetry (position, velocity, heading, episode,
                    timeout state — no goal direction / distance oracle)
  event_deltas()  → {hit, miss, brick, wall_stuck, whisker_bump} —
                    hit fires on goal-reach, then the agent respawns at
                    the start with the maze layout unchanged.
  apply_force(a)  → queue steering command (scalar in ActionDecoder scale
                    ~[-4, +4]); interpreted as turn rate.

Adaptive episode timeout: if the agent doesn't reach goal within
_timeout_ticks, respawn and double the timeout. On success, halve it.
Prevents infinite pathless wandering without hand-picking a cutoff.
"""
from collections import deque
from typing import Optional
import math
import numpy as np
import cv2


class _MazeSim:
    """Fixed 5×5 grid maze + continuous-time rodent physics.

    Agent always moves forward at SPEED; the scalar force command rotates
    heading. This maps the existing 1D action space (LEFT/IDLE/RIGHT) onto
    a 2D body without expanding the EFE action-bin dimensionality."""

    GRID              = 5
    MAX_SPEED         = 3.5          # px / tick (forward)
    MIN_SPEED         = 1.2          # even IDLE keeps the agent drifting
    TURN_RATE         = 0.18         # rad / tick at |force|=1
    FORCE_INPUT_SCALE = 4.0          # ActionDecoder emits ±4
    AGENT_R           = 6            # 12 px disc
    WHISKER_RAYS      = 8            # N, NE, E, SE, S, SW, W, NW
    WHISKER_MAX_PX    = 96           # ray cast cap
    GOAL_RADIUS_FRAC  = 0.30         # goal disc radius = this × cell_size
    MAX_STARVE_TICKS  = 4000         # ≈200s at 20Hz before full starvation
    SCENT_RANGE_PX    = 256.0        # exp-falloff length (≈2 cells at 640/5)
    SCENT_MAX_PX      = 800.0        # ray cap for scent march (canvas diag)
    # Pheromone trail — anti-circular-path aversion. The agent lays a scent
    # where it walks; recent trail is aversive (discourages retreading),
    # older trail fades. Radius is sub-cell so only re-entering the same
    # local neighborhood triggers aversion; moving a corridor away clears it.
    TRAIL_DECAY       = 0.99         # per-tick weight decay (~100-tick half-life ≈ 5s)
    TRAIL_RADIUS_PX   = 20.0         # Gaussian falloff length (< MIN_SPEED × SKIP)
    TRAIL_MIN_WEIGHT  = 0.02         # drop evaporated trail points
    TRAIL_MAXLEN      = 400          # hard cap (20s of history at 20Hz)
    TRAIL_NORM_K      = 3.0          # saturation: pheromone = 1 - exp(-sum/K)
    # Spinal wall-escape reflex — fires when the body is grinding against a
    # wall for multiple ticks with no directional escape. Bypasses the brain
    # with a hard turn toward the clearer hemisphere. Biological analog: rat
    # barrel-cortex → motor-cortex direct loop (doesn't wait for hippocampus).
    REFLEX_ENTER_THRESH = 0.75       # max whisker to start counting stuck ticks
    REFLEX_EXIT_THRESH  = 0.40       # max whisker to release reflex
    REFLEX_TRIGGER_TICKS = 5         # consecutive ticks of close contact before firing

    def __init__(self, width: int = 640, height: int = 480, seed: int = 0):
        self.width  = int(width)
        self.height = int(height)
        self.cell_w = self.width  // self.GRID
        self.cell_h = self.height // self.GRID
        self._rng = np.random.default_rng(seed)

        # adj[c][r] = set of (c', r') that are reachable (no wall between).
        # Generated by a seeded DFS carve — the same seed always produces
        # the same maze, so the layout is effectively hand-authored even
        # though it's generated programmatically.
        self.adj = [[set() for _ in range(self.GRID)] for _ in range(self.GRID)]
        self._carve_maze()

        # Precompute wall segments for rendering / ray-casting.
        self._walls = self._compute_walls()

        # Goals — multi-food (2026-04-21). Three food discs at different
        # corners of the maze. Agent starts top row; any corner food is a
        # valid target. More anchors in the V-map, more eat events per run,
        # and the "nearest food" distance is shorter on average, which
        # exposes the scent gradient to a wider slice of the map.
        self.goal_r = min(self.cell_w, self.cell_h) * self.GOAL_RADIUS_FRAC
        self.goals: list = []
        for gc, gr in [(self.GRID - 1, self.GRID - 1),
                       (self.GRID - 1, 0),
                       (0, self.GRID - 1)]:
            self.goals.append([
                (gc + 0.5) * self.cell_w,
                (gr + 0.5) * self.cell_h,
                self.goal_r,
            ])
        # Aliases for legacy accessors (used by scent whiskers etc).
        self.goal_x = self.goals[0][0]
        self.goal_y = self.goals[0][1]

        self.episode_count = 0
        # Progressive spawn: top row cells 0..GRID-1 are all valid starting
        # points. Each eat advances the spawn column by one (wrapping), so the
        # agent faces the maze from a different entry each episode — forces
        # the value landscape to generalize across start locations rather
        # than baking in one specific opening approach.
        self._spawn_col: int = 0
        # Pheromone trail storage: list of [x, y, weight] (list so we can
        # decay in place). Cleared on every reset_pose (new episode = fresh
        # smell field). Distinct from _trail below which is a UI-only
        # (x, y) breadcrumb deque for render_topdown().
        self._pheromone_trail: list = []
        # Wall-escape reflex state.
        self._stuck_count: int = 0
        self._reflex_active: bool = False
        self.reset_pose()

    # ------------------------------------------------------------------ Maze carving
    def _carve_maze(self) -> None:
        visited = {(0, 0)}
        stack   = [(0, 0)]
        while stack:
            c, r = stack[-1]
            candidates = []
            for dc, dr in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                nc, nr = c + dc, r + dr
                if 0 <= nc < self.GRID and 0 <= nr < self.GRID and (nc, nr) not in visited:
                    candidates.append((nc, nr))
            if not candidates:
                stack.pop()
                continue
            nc, nr = candidates[int(self._rng.integers(len(candidates)))]
            self.adj[c][r].add((nc, nr))
            self.adj[nc][nr].add((c, r))
            visited.add((nc, nr))
            stack.append((nc, nr))

    def _compute_walls(self) -> list:
        """Return list of ((x0, y0), (x1, y1)) wall segments in pixel coords.
        Includes the outer border and every internal edge between cells that
        are NOT in each other's adjacency sets."""
        walls = []
        w, h, cw, ch = self.width, self.height, self.cell_w, self.cell_h
        # Outer border
        walls.append(((0, 0), (w - 1, 0)))
        walls.append(((0, h - 1), (w - 1, h - 1)))
        walls.append(((0, 0), (0, h - 1)))
        walls.append(((w - 1, 0), (w - 1, h - 1)))
        # Internal verticals: between (c-1, r) and (c, r) for c in 1..GRID-1
        for c in range(1, self.GRID):
            for r in range(self.GRID):
                if (c, r) not in self.adj[c - 1][r]:
                    x = c * cw
                    walls.append(((x, r * ch), (x, (r + 1) * ch)))
        # Internal horizontals: between (c, r-1) and (c, r)
        for r in range(1, self.GRID):
            for c in range(self.GRID):
                if (c, r) not in self.adj[c][r - 1]:
                    y = r * ch
                    walls.append(((c * cw, y), ((c + 1) * cw, y)))
        return walls

    # ------------------------------------------------------------------ Pose lifecycle
    def reset_pose(self, advance_col: bool = False) -> None:
        """Respawn at a top-row cell center with a randomized heading. When
        advance_col is True, step the spawn column forward (mod GRID) — used
        on goal-reach so successive eats begin from different cells, forcing
        the substrate to generalize across start locations. Starvation /
        timeout respawns keep the same column (the agent hasn't earned the
        advance)."""
        if advance_col:
            self._spawn_col = (self._spawn_col + 1) % self.GRID
        self.x       = (self._spawn_col + 0.5) * self.cell_w
        self.y       = 0.5 * self.cell_h
        self.heading = float(self._rng.uniform(-math.pi, math.pi))
        self.energy  = 1.0
        self._pheromone_trail = []   # fresh scent field per episode
        self._stuck_count     = 0
        self._reflex_active   = False

    # ------------------------------------------------------------------ Physics step
    def _wall_escape_reflex(self, whiskers: list) -> Optional[float]:
        """Return a reflex force ∈ [-1, 1] if the body should perform a
        spinal wall-escape turn, else None. Fires after N consecutive ticks
        with any whisker ≥ ENTER_THRESH, releases when max drops below
        EXIT_THRESH. Turns AWAY from the denser hemisphere (relative to
        current heading): more walls on the left → hard right turn."""
        max_w = max(whiskers) if whiskers else 0.0
        if max_w >= self.REFLEX_ENTER_THRESH:
            self._stuck_count += 1
        else:
            self._stuck_count = 0
        if max_w < self.REFLEX_EXIT_THRESH:
            self._reflex_active = False
        if (not self._reflex_active and
                self._stuck_count >= self.REFLEX_TRIGGER_TICKS):
            self._reflex_active = True

        if not self._reflex_active:
            return None

        # Compare whisker hemispheres relative to heading. Whisker k's
        # absolute angle is k*(2π/N) - π/2 (N = north = -π/2 in screen
        # coords). rel = angle - heading, normalized to [-π, π]: positive
        # → right side (clockwise from heading), negative → left side.
        left_sum, right_sum = 0.0, 0.0
        for k, w in enumerate(whiskers):
            angle = k * (2.0 * math.pi / self.WHISKER_RAYS) - math.pi / 2.0
            rel = angle - self.heading
            while rel >  math.pi: rel -= 2.0 * math.pi
            while rel < -math.pi: rel += 2.0 * math.pi
            if rel > 0:
                right_sum += w
            else:
                left_sum  += w
        # +force turns the heading by +TURN_RATE (see step below); that's a
        # clockwise / right rotation. Turn AWAY from the denser side.
        return 1.0 if left_sum > right_sum else -1.0

    def step(self, force_norm: float) -> None:
        """force_norm in [-1, 1]: negative turns left, positive turns right.
        Forward speed scales from MIN_SPEED (|force|≈1) to MAX_SPEED (|force|≈0)
        — keeps the agent moving even during hard turns, but committing to a
        direction is rewarded with higher translational speed."""
        # Drain energy every tick — hunger is a body property, not a reward.
        self.energy = max(0.0, self.energy - 1.0 / self.MAX_STARVE_TICKS)

        # Spinal reflex: if whiskers scream for long enough, override the
        # brain's command with a directional wall-escape turn.
        # Disabled 2026-04-21: first run showed regression (0 eats vs 1
        # prior). Hypothesis: reflex rescues from walls, clean-travel DA
        # fires on the rescue motion, brain's chosen action gets credit
        # for the reflex's work → Goodhart attractor on "idle in open
        # space." Ablating to confirm.
        # reflex = self._wall_escape_reflex(self.cast_whiskers())
        # if reflex is not None:
        #     force_norm = reflex

        f = float(np.clip(force_norm, -1.0, 1.0))
        self.heading += f * self.TURN_RATE
        # Normalize heading to (-pi, pi]
        if self.heading >  math.pi:  self.heading -= 2 * math.pi
        if self.heading < -math.pi:  self.heading += 2 * math.pi
        speed = self.MIN_SPEED + (self.MAX_SPEED - self.MIN_SPEED) * (1.0 - abs(f))

        dx = speed * math.cos(self.heading)
        dy = speed * math.sin(self.heading)

        # Axis-separated collision resolution (cell-adjacency test).
        cx_cur = int(self.x // self.cell_w)
        cy_cur = int(self.y // self.cell_h)

        new_x = self.x + dx
        cx_new = int(new_x // self.cell_w)
        if cx_new == cx_cur:
            self.x = new_x
        else:
            nc = max(0, min(self.GRID - 1, cx_new))
            if (nc, cy_cur) in self.adj[cx_cur][cy_cur]:
                self.x = new_x
            else:
                # Clamp just inside the current cell's edge
                if cx_new > cx_cur:
                    self.x = (cx_cur + 1) * self.cell_w - self.AGENT_R - 0.5
                else:
                    self.x = cx_cur * self.cell_w + self.AGENT_R + 0.5

        cx_cur = int(self.x // self.cell_w)    # x may have moved
        new_y = self.y + dy
        cy_new = int(new_y // self.cell_h)
        if cy_new == cy_cur:
            self.y = new_y
        else:
            nr = max(0, min(self.GRID - 1, cy_new))
            if (cx_cur, nr) in self.adj[cx_cur][cy_cur]:
                self.y = new_y
            else:
                if cy_new > cy_cur:
                    self.y = (cy_cur + 1) * self.cell_h - self.AGENT_R - 0.5
                else:
                    self.y = cy_cur * self.cell_h + self.AGENT_R + 0.5

        # Final clamp to canvas
        self.x = float(np.clip(self.x, self.AGENT_R + 1, self.width  - self.AGENT_R - 1))
        self.y = float(np.clip(self.y, self.AGENT_R + 1, self.height - self.AGENT_R - 1))

        # Update pheromone trail: decay existing weights, drop evaporated
        # points, append current pose. Bounded by TRAIL_MAXLEN so cost is
        # strictly O(N≤400) per tick.
        decayed: list = []
        for pt in self._pheromone_trail:
            pt[2] *= self.TRAIL_DECAY
            if pt[2] > self.TRAIL_MIN_WEIGHT:
                decayed.append(pt)
        decayed.append([self.x, self.y, 1.0])
        if len(decayed) > self.TRAIL_MAXLEN:
            decayed = decayed[-self.TRAIL_MAXLEN:]
        self._pheromone_trail = decayed

    TRAIL_SKIP_RECENT = 40   # ignore last ~2s of trail (forward-drift corridor)

    def pheromone_at(self, px: float, py: float) -> float:
        """Staleness at (px, py) ∈ [0, 1]. Gaussian falloff with distance;
        decayed weight per tick. Recent TRAIL_SKIP_RECENT points are excluded
        so the agent's just-laid scent (which is always within radius during
        steady forward drift) doesn't saturate the channel. Raw sum is
        squashed through 1 - exp(-sum/K) so values stay in [0, 1] regardless
        of trail density — steady forward motion reads near-zero, returning
        to a crossed corridor reads ~0.3-0.6, spinning-in-place saturates to
        ~1.0 over ~30 ticks."""
        if len(self._pheromone_trail) <= self.TRAIL_SKIP_RECENT:
            return 0.0
        r2 = self.TRAIL_RADIUS_PX * self.TRAIL_RADIUS_PX
        total = 0.0
        for pt in self._pheromone_trail[:-self.TRAIL_SKIP_RECENT]:
            dx = px - pt[0]
            dy = py - pt[1]
            d2 = dx * dx + dy * dy
            if d2 > 4.0 * r2:
                continue
            total += pt[2] * math.exp(-d2 / r2)
        return float(1.0 - math.exp(-total / self.TRAIL_NORM_K))

    # ------------------------------------------------------------------ Whisker raycast
    def cast_whiskers(self) -> list:
        """Return 8 whisker readings ∈ [0, 1]: 0 = clear, 1 = touching a wall.
        Direction order: N, NE, E, SE, S, SW, W, NW (compass, clockwise from N)."""
        readings = []
        for k in range(self.WHISKER_RAYS):
            angle = k * (2 * math.pi / self.WHISKER_RAYS) - math.pi / 2   # N = -pi/2
            dist = self._ray_distance(angle)
            # Normalize: 0 px → 1.0 (touching); WHISKER_MAX_PX → 0.0 (clear).
            readings.append(float(max(0.0, 1.0 - dist / self.WHISKER_MAX_PX)))
        return readings

    def _ray_distance(self, angle: float) -> float:
        """Distance from agent center to the nearest wall along *angle* (or
        WHISKER_MAX_PX if no wall is hit within range). March in 2-pixel steps
        — cheap and accurate enough for an 8-direction proximity sense."""
        step = 2.0
        x, y = self.x, self.y
        dx = step * math.cos(angle)
        dy = step * math.sin(angle)
        for i in range(1, int(self.WHISKER_MAX_PX / step) + 1):
            x += dx
            y += dy
            if x < 0 or x >= self.width or y < 0 or y >= self.height:
                return float(i * step)
            # Cell-adjacency test: if we've crossed into a non-adjacent cell,
            # there's a wall between. This matches what step() enforces.
            cx = int(x // self.cell_w)
            cy = int(y // self.cell_h)
            ox = int((x - dx) // self.cell_w)
            oy = int((y - dy) // self.cell_h)
            if (cx, cy) != (ox, oy):
                if not (0 <= cx < self.GRID and 0 <= cy < self.GRID):
                    return float(i * step)
                if (cx, cy) not in self.adj[ox][oy]:
                    return float(i * step)
        return float(self.WHISKER_MAX_PX)

    # ------------------------------------------------------------------ Scent raycast
    def cast_scent(self) -> list:
        """Return 8 directional scent readings ∈ [0, 1]. Each whisker's
        reading is the peak scent intensity sampled along its ray until the
        ray hits a wall or exits the canvas. Scent at a point (x, y) is
        exp(-euclid(point, goal) / SCENT_RANGE_PX), so walls occlude the
        smell — an agent standing adjacent to the goal cell with a wall
        between gets near-zero scent; from an open corridor with clear
        line-of-sight it gets a strong gradient pointing toward food."""
        readings = []
        for k in range(self.WHISKER_RAYS):
            angle = k * (2 * math.pi / self.WHISKER_RAYS) - math.pi / 2
            readings.append(self._scent_along_ray(angle))
        return readings

    def _scent_along_ray(self, angle: float) -> float:
        step = 4.0
        x, y = self.x, self.y
        dx = step * math.cos(angle)
        dy = step * math.sin(angle)
        max_scent = 0.0
        n_steps = int(self.SCENT_MAX_PX / step)
        for _ in range(1, n_steps + 1):
            nx = x + dx
            ny = y + dy
            if nx < 0 or nx >= self.width or ny < 0 or ny >= self.height:
                break
            cx = int(nx // self.cell_w)
            cy = int(ny // self.cell_h)
            ox = int(x  // self.cell_w)
            oy = int(y  // self.cell_h)
            if (cx, cy) != (ox, oy):
                if not (0 <= cx < self.GRID and 0 <= cy < self.GRID):
                    break
                if (cx, cy) not in self.adj[ox][oy]:
                    break
            # Nearest goal's scent dominates — each food emits its own
            # exp-falloff plume, agent smells the strongest at this point.
            best = 0.0
            for gx, gy, _gr in self.goals:
                d_goal = math.hypot(nx - gx, ny - gy)
                sg = math.exp(-d_goal / self.SCENT_RANGE_PX)
                if sg > best:
                    best = sg
            if best > max_scent:
                max_scent = best
            x, y = nx, ny
        return float(max_scent)

    # ------------------------------------------------------------------ Rendering
    FOV_RAD       = math.pi / 2.0     # 90° field of view
    RAY_STEP_PX   = 2.0               # ray-march increment
    MAX_VIEW_PX   = 800.0             # ray cap (canvas diagonal is ~800 for 640×480)

    def _ray_first_person(self, angle: float):
        """March a single ray from the agent position at *angle*. Returns
        (distance_px, hit) where hit is 'wall', 'goal', or 'none'. Goal is
        tested every step by disc-proximity; walls by cell-adjacency (same
        test the physics uses, so what the agent sees matches what it
        bumps into)."""
        x, y = self.x, self.y
        dx = self.RAY_STEP_PX * math.cos(angle)
        dy = self.RAY_STEP_PX * math.sin(angle)
        max_steps = int(self.MAX_VIEW_PX / self.RAY_STEP_PX)
        prev_cx = int(x // self.cell_w)
        prev_cy = int(y // self.cell_h)
        for i in range(1, max_steps + 1):
            x += dx
            y += dy
            # Out of canvas → treat as hitting the outer border.
            if x < 0 or x >= self.width or y < 0 or y >= self.height:
                return (i * self.RAY_STEP_PX, "wall")
            # Goal disc hit? (any of the active goals)
            for gx, gy, gr in self.goals:
                if (x - gx) ** 2 + (y - gy) ** 2 <= gr * gr:
                    return (i * self.RAY_STEP_PX, "goal")
            cx = int(x // self.cell_w)
            cy = int(y // self.cell_h)
            if (cx, cy) != (prev_cx, prev_cy):
                if not (0 <= cx < self.GRID and 0 <= cy < self.GRID):
                    return (i * self.RAY_STEP_PX, "wall")
                if (cx, cy) not in self.adj[prev_cx][prev_cy]:
                    return (i * self.RAY_STEP_PX, "wall")
                prev_cx, prev_cy = cx, cy
        return (self.MAX_VIEW_PX, "none")

    # Trail buffer for the top-down observer view. Not consumed by the brain —
    # purely for human debugging. Deque is lazy-init on first render_topdown().
    _trail = None
    TRAIL_LEN = 120

    def render_topdown(self) -> np.ndarray:
        """Observer-only top-down BGR frame. NOT fed to the EPM — the brain
        still consumes render() (first-person). This exists so a human can
        watch where the agent is while it plays, without contaminating the
        retinal input.

        Draws: walls (grey), goal disc (green), agent disc (magenta) with
        a heading pointer, recent path (fading trail), and a small energy
        bar along the top edge."""
        from collections import deque as _deque
        if self._trail is None:
            self._trail = _deque(maxlen=self.TRAIL_LEN)
        self._trail.append((float(self.x), float(self.y)))

        H, W = self.height, self.width
        frame = np.full((H, W, 3), 20, dtype=np.uint8)   # near-black backdrop

        # Cell grid (very faint) — helps read the maze topology at a glance.
        grid_color = (45, 45, 45)
        for c in range(self.GRID + 1):
            x = int(c * self.cell_w)
            cv2.line(frame, (x, 0), (x, H - 1), grid_color, 1)
        for r in range(self.GRID + 1):
            y = int(r * self.cell_h)
            cv2.line(frame, (0, y), (W - 1, y), grid_color, 1)

        # Walls (2 px wide, near-white).
        for (x0, y0), (x1, y1) in self._walls:
            cv2.line(frame, (int(x0), int(y0)), (int(x1), int(y1)),
                     (200, 200, 200), 2)

        # Goal discs — solid green circle with a thin bright ring, one per
        # active food.
        for gx, gy, gr in self.goals:
            gx_i, gy_i, gr_i = int(gx), int(gy), int(gr)
            cv2.circle(frame, (gx_i, gy_i), gr_i, (30, 200, 30), -1)
            cv2.circle(frame, (gx_i, gy_i), gr_i, (60, 255, 60), 1)

        # Fading trail — oldest dim, newest bright. Cheap 1-px dots.
        n = len(self._trail)
        for i, (tx, ty) in enumerate(self._trail):
            fade = int(60 + 140 * (i / max(1, n - 1)))   # 60..200
            cv2.circle(frame, (int(tx), int(ty)), 1, (fade, 0, fade), -1)

        # Agent disc (magenta) + heading pointer.
        ax, ay = int(self.x), int(self.y)
        cv2.circle(frame, (ax, ay), self.AGENT_R, (200, 40, 200), -1)
        cv2.circle(frame, (ax, ay), self.AGENT_R, (255, 80, 255), 1)
        hx = int(ax + 2.2 * self.AGENT_R * math.cos(self.heading))
        hy = int(ay + 2.2 * self.AGENT_R * math.sin(self.heading))
        cv2.line(frame, (ax, ay), (hx, hy), (255, 120, 255), 2)

        # Energy bar along the very top — full green → empty red.
        bar_w = int(W * 0.98)
        bar_h = 4
        x0 = (W - bar_w) // 2
        y0 = 2
        cv2.rectangle(frame, (x0, y0), (x0 + bar_w, y0 + bar_h), (60, 60, 60), -1)
        fill = int(bar_w * max(0.0, min(1.0, self.energy)))
        # interp red→green by energy (BGR)
        col = (40, int(60 + 180 * self.energy), int(200 * (1.0 - self.energy)))
        cv2.rectangle(frame, (x0, y0), (x0 + fill, y0 + bar_h), col, -1)
        return frame

    def render(self) -> np.ndarray:
        """First-person BGR frame (cv2 convention). Same (H, W, 3) uint8
        shape as top-down renderers so the retinal EPM is unchanged. Ray-
        cast Wolfenstein-style column renderer — each column is a vertical
        strip whose height = screen_h × (proj_scale / dist_forward). Shading
        falls off with distance so near walls are bright, far walls dim.

        Why first-person: a top-down view is dominated by the static maze
        layout; the agent's small disc moving across it contributes almost
        nothing to the frame embedding, so the retinal GNG collapses to a
        single node. First-person makes the agent's position the MAIN
        driver of pixel change, which is what a place-cell-forming visual
        system needs."""
        H, W = self.height, self.width
        frame = np.empty((H, W, 3), dtype=np.uint8)
        # Sky (upper half) and floor (lower half) as flat horizon bands —
        # helps the encoder distinguish "looking at wall" from "open hallway"
        # (a distant ray leaves floor/sky visible, a close wall blocks them).
        frame[:H // 2, :] = (80, 60, 40)     # sky: desaturated blue-grey (BGR)
        frame[H // 2:, :] = (40, 50, 70)     # floor: warm brown

        proj_scale = self.cell_w * 0.35      # walls at ~1 cell away fill ~half-height; sky/floor visible down long corridors
        num_rays = W
        fov = self.FOV_RAD
        for col in range(num_rays):
            ang = self.heading - fov * 0.5 + fov * (col / max(1, num_rays - 1))
            dist, hit = self._ray_first_person(ang)
            if hit == "none":
                continue
            # Fish-eye correction: use forward-projected distance for sizing.
            forward_dist = max(1.0, dist * math.cos(ang - self.heading))
            strip_h = min(H, int(H * proj_scale / forward_dist))
            y0 = max(0, (H - strip_h) // 2)
            y1 = min(H, y0 + strip_h)
            shade = max(30, int(240 - forward_dist * 1.6))
            if hit == "goal":
                # Saturated green; no distance shading so it's always salient
                # when visible (a known visual landmark).
                color = (30, 220, 30)
            else:
                color = (shade, shade, shade)
            frame[y0:y1, col] = color
        return frame


class MazeEnv:
    """HeadlessBreakout-compatible wrapper around _MazeSim.

    Episode timeout self-tunes: starts at 5000 ticks, doubles on timeout,
    halves on goal-reach. No external scheduler — the body's own success
    history adjusts how long it's willing to keep searching before
    resetting. Prevents infinite pathless wandering without a hand-set
    cap that biases the measurement."""

    _TIMEOUT_MIN  = 500
    _TIMEOUT_MAX  = 40000
    _TIMEOUT_INIT = 5000

    def __init__(self, width: int = 640, height: int = 480, seed: int = 0):
        self._game = _MazeSim(width=width, height=height, seed=seed)
        self._last_force_norm: float = 0.0
        self._telemetry_disabled: bool = False
        self._prev_episode: int = 0

        self._timeout_ticks: int = self._TIMEOUT_INIT
        self._ticks_since_reset: int = 0
        self._time_to_goal_history: deque = deque(maxlen=20)
        self._last_time_to_goal: int = 0
        self._starvation_count: int = 0
        self._energy_at_last_hit: float = 1.0
        self._prev_starvation_count: int = 0
        self._prev_max_whisker: float = 0.0
        self._bump_threshold: float = 0.85

    # ---- Runner-facing interface -----------------------------------------
    def tick(self) -> np.ndarray:
        self._game.step(self._last_force_norm)
        self._ticks_since_reset += 1

        # Goal reach? Multi-food: eat ANY goal, then respawn the eaten one
        # in a different random cell so the target density stays constant.
        ate_idx = None
        for i, (gx, gy, gr) in enumerate(self._game.goals):
            if (self._game.x - gx) ** 2 + (self._game.y - gy) ** 2 < gr * gr:
                ate_idx = i
                break
        if ate_idx is not None:
            self._game.episode_count += 1
            self._time_to_goal_history.append(self._ticks_since_reset)
            self._last_time_to_goal = self._ticks_since_reset
            # Capture energy at the moment of eating — runner reads this to
            # scale the blame pulse (fast eats = nearly full energy = big pulse).
            self._energy_at_last_hit = float(self._game.energy)
            # Adaptive timeout: halve on success (floored at MIN).
            self._timeout_ticks = max(self._TIMEOUT_MIN, int(self._timeout_ticks * 0.5))
            self._ticks_since_reset = 0
            # Food respawns immediately AT THE SAME POSITION. This makes
            # the env a stable foraging task: 3 fixed feeders, the agent
            # eats → gets tossed back to start → food is right back where
            # it was. Stable place→food anchors can form in the V-map
            # because the food coordinates don't drift between eats.
            # Random respawn was previously trialed but fragmented the
            # valence anchor across constantly-moving cells, defeating
            # value-iteration propagation.
            self._game.reset_pose()   # also replenishes energy to 1.0
        elif self._game.energy <= 0.0:
            # Starvation: body cycles, no blame event (the aversion was
            # delivered tick-by-tick through the interoceptive channel).
            self._starvation_count += 1
            self._ticks_since_reset = 0
            self._game.reset_pose()
        elif self._ticks_since_reset >= self._timeout_ticks:
            # Timeout: double timeout, keep the maze, reset agent pose only.
            self._timeout_ticks = min(self._TIMEOUT_MAX, int(self._timeout_ticks * 2))
            self._ticks_since_reset = 0
            self._game.reset_pose()

        return self._game.render()

    def render_topdown(self) -> np.ndarray:
        """Observer view for the UI. Brain still eats first-person via tick()."""
        return self._game.render_topdown()

    def state(self) -> dict:
        g = self._game
        # Note: _telemetry_disabled is a Pong/Breakout oracle-blinding flag
        # (hides ball_x from the agent). Maze has no oracle channel — pos,
        # heading, and whiskers ARE the body, not cheats — so we ignore it.
        return {
            "maze_x":            g.x,
            "maze_y":            g.y,
            "maze_w":            g.width,
            "maze_h":            g.height,
            "heading":           g.heading,
            "energy":            float(g.energy),
            "episode":           g.episode_count,
            "ticks_since_reset": self._ticks_since_reset,
            "timeout_ticks":     self._timeout_ticks,
            "last_time_to_goal": self._last_time_to_goal,
            "starvations":       self._starvation_count,
            "energy_at_last_hit": self._energy_at_last_hit,
            "whiskers":          g.cast_whiskers(),
            "scent_whiskers":    g.cast_scent(),
            "pheromone":         g.pheromone_at(g.x, g.y),
        }

    def event_deltas(self) -> dict:
        g = self._game
        hit = g.episode_count > self._prev_episode
        self._prev_episode = g.episode_count
        starved = self._starvation_count > self._prev_starvation_count
        self._prev_starvation_count = self._starvation_count
        # Edge-triggered whisker_bump: fires on the tick that max-whisker
        # crosses the bump threshold from below. Prevents spam during
        # sustained wall contact (aversion stays continuous via on_whisker).
        max_w = float(max(g.cast_whiskers()))
        bump = (max_w >= self._bump_threshold and
                self._prev_max_whisker < self._bump_threshold)
        self._prev_max_whisker = max_w
        return {
            "hit":          hit,
            "miss":         False,
            "brick":        False,
            "wall_stuck":   False,
            "whisker_bump": bump,
            "starved":      starved,
        }

    def set_brain_mode(self) -> None: pass

    def set_velocity(self, v: float) -> None:
        # Compatibility shim — map raw velocity to normalised steering.
        self._last_force_norm = float(np.clip(v / 10.0, -1.0, 1.0))

    def apply_force(self, accel: float) -> None:
        """Runner passes ActionDecoder scalar (±FORCE_INPUT_SCALE); we map
        to [-1, 1] and interpret as turn command."""
        self._last_force_norm = float(np.clip(accel / _MazeSim.FORCE_INPUT_SCALE,
                                              -1.0, 1.0))

    def set_telemetry_disabled(self, disabled: bool) -> None:
        # No-op for maze: there is no oracle channel to blind.
        self._telemetry_disabled = bool(disabled)

    # ---- No-op shims (Breakout-only modes) -------------------------------
    def set_rally_mode(self)    -> None: pass
    def set_observer_mode(self) -> None: pass
    def set_mode(self, mode: str) -> None: pass
